#!/usr/bin/env node
// Writes .env.local for the app from the running local Supabase stack (`supabase start`).
// Only the public URL and publishable key go to browser code. The public booking pages also
// need the server-only booking_api login (D-21): this script gives that role a fresh random
// password on the local database and writes its connection string, plus a random secret for
// hashing client IPs. The Supabase secret/service-role key is never written here.
import { execSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import pg from 'pg';

const status = JSON.parse(execSync('npx supabase status -o json', { encoding: 'utf8' }));
// Re-running keeps the existing booking password and secret, so a running dev server keeps working.
const previous = existsSync('.env.local') ? readFileSync('.env.local', 'utf8') : '';
const previousUrl = previous.match(/^BOOKING_DATABASE_URL=(.+)$/m)?.[1];
const password = previousUrl ? decodeURIComponent(new URL(previousUrl).password) : randomBytes(24).toString('hex');
const hashSecret = previous.match(/^BOOKING_HASH_SECRET=([0-9a-f]{64})$/m)?.[1] ?? randomBytes(32).toString('hex');
const admin = new pg.Client({ connectionString: status.DB_URL });
await admin.connect();
await admin.query(`alter role booking_api with login password '${password}'`);
await admin.end();
const bookingUrl = status.DB_URL.replace(/\/\/[^@]+@/, `//booking_api:${password}@`);

const lines = [
  '# Generated by `npm run env:local` from the local Supabase stack. Do not commit.',
  `NEXT_PUBLIC_SUPABASE_URL=${status.API_URL}`,
  `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${status.PUBLISHABLE_KEY}`,
  'NEXT_PUBLIC_SITE_URL=http://localhost:3000',
  '# invite (pilot) | open — open also needs `enable_signup = true` in supabase/config.toml',
  'AUTH_SIGNUP_MODE=invite',
  '# Server-only: public booking pages (restricted booking_api role) and the IP-hash secret.',
  `BOOKING_DATABASE_URL=${bookingUrl}`,
  `BOOKING_HASH_SECRET=${hashSecret}`,
  '',
];
writeFileSync('.env.local', lines.join('\n'));
console.log('Wrote .env.local (booking_api login enabled on the local database)');
